import { z } from 'zod';
import { OPTION_SELECTORS, type Step, stepSchema } from './definition.ts';
import { type Locator, locatorSchema } from './locator.ts';
import { parseTemplate } from './templates.ts';

/**
 * Recorder contracts (PROJECT_RULES §8).
 *
 * The recorder script in the test page sends events through a Playwright binding; the runner
 * validates them with `pageEventSchema` (the page is untrusted), stores them in order, and adds
 * its own events (navigation, notices). The draft steps are derived from the stored events by
 * `buildRecordedSteps` — a recording never changes a test until the tester saves it.
 */

/** Keys the recorder records; everything else is typed text or ignored. */
export const RECORDER_KEYS = ['Enter', 'Tab', 'Escape'] as const;

/** Things the recorder cannot turn into steps; each is reported, never skipped silently. */
export const PAGE_UNSUPPORTED = ['iframe', 'shadowDom', 'fileInput', 'dragAndDrop', 'unsupportedField'] as const;
export const RUNNER_NOTICES = [
  'iframe',
  'popup',
  'offsiteNavigation',
  'browserClosed',
  'timeLimit',
  'runnerStopped',
  'eventLimit',
  'invalidEvent',
] as const;

export const RECORDER_WARNING_CODES = [
  'iframe',
  'shadowDom',
  'fileInput',
  'dragAndDrop',
  'unsupportedField',
  'popup',
  'offsiteNavigation',
  'browserClosed',
  'timeLimit',
  'runnerStopped',
  'eventLimit',
  'invalidEvent',
  'fragileLocator',
  'passwordField',
  'bracesInValue',
  'stepLimit',
] as const;
export type RecorderWarningCode = (typeof RECORDER_WARNING_CODES)[number];

/** Generated by the page script per event; duplicates are rejected (PROJECT_RULES §8, DUPLICATE_EVENT). */
const clientEventId = z.string().regex(/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/);
const target = {
  clientEventId,
  locator: locatorSchema,
  /** No stable locator was unique on the page; the draft step gets a warning. */
  fragile: z.boolean(),
};

export const pageEventSchema = z.discriminatedUnion('kind', [
  z.strictObject({ kind: z.literal('click'), ...target }),
  z.strictObject({
    kind: z.literal('fill'),
    ...target,
    value: z.string().max(2000),
    /** Password fields: the value is never sent; the draft uses a secret placeholder. */
    password: z.boolean(),
  }),
  z.strictObject({
    kind: z.literal('select'),
    ...target,
    option: z.strictObject({ by: z.enum(OPTION_SELECTORS), value: z.string().min(1).max(500) }),
  }),
  z.strictObject({ kind: z.literal('check'), ...target }),
  z.strictObject({ kind: z.literal('uncheck'), ...target }),
  z.strictObject({
    kind: z.literal('press'),
    clientEventId,
    key: z.enum(RECORDER_KEYS),
    locator: locatorSchema.optional(),
    fragile: z.boolean(),
  }),
  /** Checks the tester added explicitly with the overlay's "check" buttons (never guessed). */
  z.strictObject({ kind: z.literal('assertVisible'), ...target }),
  z.strictObject({ kind: z.literal('assertText'), ...target, text: z.string().min(1).max(500) }),
  z.strictObject({ kind: z.literal('unsupported'), clientEventId, what: z.enum(PAGE_UNSUPPORTED) }),
  /** "Stop recording" in the in-page overlay; not stored as an event. */
  z.strictObject({ kind: z.literal('stop'), clientEventId }),
]);
export type PageEvent = z.infer<typeof pageEventSchema>;

/** Events the runner itself adds. */
export const runnerEventSchema = z.discriminatedUnion('kind', [
  /** Navigation the tester made directly (address bar, back), not caused by a recorded action. */
  z.strictObject({ kind: z.literal('navigate'), url: z.string().min(1).max(2000) }),
  z.strictObject({ kind: z.literal('notice'), code: z.enum(RUNNER_NOTICES) }),
]);

export type RecordedEvent = Exclude<PageEvent, { kind: 'stop' }> | z.infer<typeof runnerEventSchema>;

export interface RecorderWarning {
  code: RecorderWarningCode;
  /** Draft step the warning is about, if any. */
  stepId?: string;
  /** How often a page-level warning happened. */
  count: number;
}

const MAX_MAIN_STEPS = 200;
const MAX_NAME_TARGET = 60;

function targetName(locator: Locator): string {
  const raw = (() => {
    switch (locator.kind) {
      case 'role':
        return locator.name;
      case 'id':
        return `#${locator.value}`;
      case 'attribute':
        return `${locator.name}=${locator.value}`;
      default:
        return locator.value;
    }
  })();
  return raw.length > MAX_NAME_TARGET ? `${raw.slice(0, MAX_NAME_TARGET - 1)}…` : raw;
}

const sameLocator = (a: Locator | undefined, b: Locator | undefined) => JSON.stringify(a) === JSON.stringify(b);

/**
 * Turns recorded events (in sequence order) into draft main steps:
 * - starts with "Open <startPath>";
 * - consecutive fills of the same field keep only the last value (one step, not one per key);
 * - password values become {{secrets.password}} with a warning — the typed value is never stored;
 * - values that would be read as templates ("{{") are left empty with a warning;
 * - unsupported actions and notices become warnings, never silent gaps.
 * Checks are never guessed: only those the tester picked with the overlay's check buttons are added.
 */
export function buildRecordedSteps(events: readonly RecordedEvent[], startPath: string): { steps: Step[]; warnings: RecorderWarning[] } {
  const steps: Step[] = [];
  const warnings: RecorderWarning[] = [];
  let counter = 0;
  const nextId = () => `rec-${++counter}`;
  const warnPage = (code: RecorderWarningCode) => {
    const existing = warnings.find((w) => w.code === code && w.stepId === undefined);
    if (existing) existing.count += 1;
    else warnings.push({ code, count: 1 });
  };
  const warnStep = (code: RecorderWarningCode, stepId: string) => {
    if (!warnings.some((w) => w.code === code && w.stepId === stepId)) warnings.push({ code, stepId, count: 1 });
  };
  /** Template fields: text the tester typed must not be read as {{...}} references. */
  const literal = (value: string, stepId: string) => {
    if (parseTemplate(value).ok) return value;
    warnStep('bracesInValue', stepId);
    return '';
  };
  const push = (step: Step) => {
    if (steps.length >= MAX_MAIN_STEPS) {
      warnPage('stepLimit');
      return;
    }
    steps.push(stepSchema.parse(step));
  };

  push({ id: nextId(), name: `Open ${startPath}`, type: 'navigate', url: startPath });

  for (const event of events) {
    const last = steps.at(-1);
    switch (event.kind) {
      case 'navigate': {
        if (last?.type === 'navigate') {
          steps[steps.length - 1] = { ...last, name: `Open ${event.url}`, url: event.url };
        } else push({ id: nextId(), name: `Open ${event.url}`, type: 'navigate', url: event.url });
        break;
      }
      case 'fill': {
        const value = event.password ? '{{secrets.password}}' : undefined;
        if (last?.type === 'fill' && sameLocator(last.locator, event.locator)) {
          last.value = value ?? literal(event.value, last.id);
          break;
        }
        const id = nextId();
        push({
          id,
          name: `Type into "${targetName(event.locator)}"`,
          type: 'fill',
          locator: event.locator,
          value: value ?? literal(event.value, id),
        });
        if (event.password) warnStep('passwordField', id);
        if (event.fragile) warnStep('fragileLocator', id);
        break;
      }
      case 'click':
      case 'check':
      case 'uncheck': {
        const id = nextId();
        const verb = event.kind === 'click' ? 'Click' : event.kind === 'check' ? 'Tick' : 'Untick';
        push({ id, name: `${verb} "${targetName(event.locator)}"`, type: event.kind, locator: event.locator });
        if (event.fragile) warnStep('fragileLocator', id);
        break;
      }
      case 'select': {
        const id = nextId();
        push({
          id,
          name: `Choose "${event.option.value}" in "${targetName(event.locator)}"`.slice(0, 200),
          type: 'selectOption',
          locator: event.locator,
          option: { by: event.option.by, value: literal(event.option.value, id) },
        });
        if (event.fragile) warnStep('fragileLocator', id);
        break;
      }
      case 'press': {
        const id = nextId();
        push({
          id,
          name: event.locator ? `Press ${event.key} in "${targetName(event.locator)}"` : `Press ${event.key}`,
          type: 'press',
          key: event.key,
          ...(event.locator ? { locator: event.locator } : {}),
        });
        if (event.locator && event.fragile) warnStep('fragileLocator', id);
        break;
      }
      case 'assertVisible': {
        const id = nextId();
        push({ id, name: `Check "${targetName(event.locator)}" is shown`, type: 'assertVisible', locator: event.locator });
        if (event.fragile) warnStep('fragileLocator', id);
        break;
      }
      case 'assertText': {
        // An empty expectation would pass for any text, so text that reads as a template is not used.
        if (!parseTemplate(event.text).ok) {
          warnPage('bracesInValue');
          break;
        }
        const id = nextId();
        const shown = event.text.length > MAX_NAME_TARGET ? `${event.text.slice(0, MAX_NAME_TARGET - 1)}…` : event.text;
        push({ id, name: `Check text "${shown}"`, type: 'assertText', locator: event.locator, expected: event.text, mode: 'exact' });
        if (event.fragile) warnStep('fragileLocator', id);
        break;
      }
      case 'unsupported':
        warnPage(event.what);
        break;
      case 'notice':
        warnPage(event.code);
        break;
    }
  }
  return { steps, warnings };
}
